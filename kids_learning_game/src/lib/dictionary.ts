import { WordCard, TopicKey } from '@/types/game';

type RawWord = [string, string, string, string]; // [word, displayWord, meaning, emoji]

function buildWords(lang: string, topic: TopicKey, raw: RawWord[]): WordCard[] {
  return raw.map(([word, displayWord, meaning, emoji], i) => ({
    id: `${lang}-${topic}-${String(i + 1).padStart(3, '0')}`,
    word,
    displayWord,
    meaning,
    emoji,
    topic,
  }));
}

